var REPL = [
    [/[\u2018\u2019\u02bc`\u00b4]/g, "'"],
    [/[\u201c\u201d]/g, '"'],
    [/[\u2013\u2014\u2212]/g, '-'],
    [/\u00d7/g, 'x'],
    [/\u2192/g, '>'],
    [/\u2190/g, '<'],
    [/\u2026/g, '...'],
    [/\u00a0/g, ' ']
]
var CH_W = 5
var CH_H = 7
var cache = {}

function norm(text) {
    var s = String(text === undefined || text === null ? '' : text)
    try { s = s.normalize('NFKD').replace(/[\u0300-\u036f]/g, '') } catch (e) {}
    for (var i = 0; i < REPL.length; ++i)
        s = s.replace(REPL[i][0], REPL[i][1])
    return s.toUpperCase()
}
function rows(ch) {
    if (cache[ch]) return cache[ch]
    var src = GLYPHS[ch] || GLYPHS['?']
    var r = src.split('/')
    cache[ch] = r
    return r
}
function measure(text, scale, spacing) {
    scale = scale || 1
    spacing = spacing === undefined ? 1 : spacing
    var n = norm(text).length
    if (!n) return 0
    return n * CH_W * scale + (n - 1) * spacing * scale
}
function draw(ctx, text, x, y, scale, color, spacing) {
    scale = scale || 1
    spacing = spacing === undefined ? 1 : spacing
    var str = norm(text)
    ctx.save()
    ctx.fillStyle = color || '#38ff55'
    var cx = x
    for (var i = 0; i < str.length; ++i) {
        var ch = str.charAt(i)
        if (ch !== ' ') {
            var g = rows(ch)
            for (var r = 0; r < CH_H; ++r) {
                var row = g[r] || '00000'
                for (var c = 0; c < CH_W; ++c) {
                    if (row.charAt(c) === '1')
                        ctx.fillRect(Math.round(cx + c * scale), Math.round(y + r * scale), scale, scale)
                }
            }
        }
        cx += (CH_W + spacing) * scale
    }
    ctx.restore()
}
